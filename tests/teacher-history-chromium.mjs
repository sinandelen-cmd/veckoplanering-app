import assert from 'node:assert/strict'
import {chromium} from 'playwright'
const browser=await chromium.launch({headless:true,args:['--no-sandbox']})
try{
 const page=await browser.newPage()
 await page.route('**/*',route=>['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort('blockedbyclient'))
 await page.goto('http://127.0.0.1:4177/tests/teacher-history-fixture.html')
 const plan=async()=>JSON.parse(await page.getByTestId('plan').textContent())
 const history=async()=>JSON.parse(await page.getByTestId('history').textContent())
 const title=page.getByRole('textbox',{name:'Planeringens namn'})
 await title.fill('A ändrad')
 assert.equal((await plan()).title,'A ändrad')
 assert.equal((await history()).past>0,true)
 await page.getByRole('button',{name:'Öppna planering B'}).click()
 assert.equal((await plan()).title,'Planering B')
 assert.equal((await history()).past,0)
 assert.equal(await page.getByRole('button',{name:'Ångra',exact:true}).first().isDisabled(),true)
 assert.equal(await page.getByRole('button',{name:'Gör om',exact:true}).first().isDisabled(),true)
 await title.fill('B ändrad')
 await page.getByRole('button',{name:'Ångra',exact:true}).first().click()
 assert.equal((await plan()).title,'Planering B')
 assert.equal((await plan()).classGroups[0].name,'B-klass')
 await page.getByRole('button',{name:'Gör om',exact:true}).first().click()
 assert.equal((await plan()).title,'B ändrad')
 await page.getByRole('button',{name:'Öppna planering A'}).click()
 assert.equal((await plan()).title,'Planering A')
 assert.equal((await history()).past,0)
 assert.equal(await page.getByRole('button',{name:'Ångra',exact:true}).first().isDisabled(),true)
 assert.equal((await plan()).classGroups[0].name,'A-klass')
 console.log('PASS actual teacher history hook: plan A and B isolated, undo redo never crosses saved-plan boundary')
}finally{await browser.close()}
