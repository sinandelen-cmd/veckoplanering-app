import fs from 'node:fs'
import vm from 'node:vm'
import assert from 'node:assert/strict'

const source = fs.readFileSync(new URL('../src/App.jsx', import.meta.url), 'utf8')
const start = source.indexOf('function publicationFields(')
const end = source.indexOf('function Login(', start)
assert.ok(start >= 0 && end > start, 'Publiceringsfunktionen hittades inte')
const ctx = vm.createContext({ JSON })
vm.runInContext(source.slice(start, end), ctx)
const fields = vm.runInContext('publicationFields', ctx)
const published = fields(true, false, 'min-lank', { title: 'Elevvy' })
assert.equal(published.published, true)
assert.equal(published.public_slug, 'min-lank')
assert.deepEqual(JSON.parse(published.published_content), { title: 'Elevvy' })
const draft = fields(false, false, '', null)
assert.equal(draft.published, false)
assert.equal(draft.published_content, null)
assert.equal(draft.public_slug, null)
assert.deepEqual(Object.keys(fields(false, true, 'min-lank', null)), [])
assert.match(source, /published: publish \|\| keepPublished/)
assert.match(source, /select\('published,public_slug'\)/)
assert.match(source, /publish \|\| !selectedId \? publicationFields/)
assert.doesNotMatch(source, /Boolean\(plan\.published\)/)
assert.match(source, /if \(selectedId === row\.id\) setPlan\(p => \(\{ \.\.\.p, published: false, publicSlug: '' \}\)\)/)
const unpublish = source.slice(source.indexOf('async function unpublish(row)'), source.indexOf('async function importFile(file)'))
assert.match(unpublish, /published_content: null/)
assert.match(unpublish, /public_slug: null/)
assert.match(unpublish, /\.eq\('id', row\.id\)\.eq\('user_id', session\.user\.id\)\.select\('id'\)\.single\(\)/)
assert.doesNotMatch(unpublish, /content: JSON\.stringify/)
const fromRowStart = source.indexOf('function planFromRow(')
const fromRowEnd = source.indexOf('function sanitizeForStudents(', fromRowStart)
assert.ok(fromRowStart >= 0 && fromRowEnd > fromRowStart)
const rowCtx = vm.createContext({ emptyPlan: () => ({ published: false }) })
vm.runInContext(source.slice(fromRowStart, fromRowEnd), rowCtx)
const planFromRow = vm.runInContext('planFromRow', rowCtx)
const staleRow = { content: JSON.stringify({ kind: 'arsplanering-v2', published: true }), published: false }
assert.equal(planFromRow(staleRow).published, false, 'Databasens publiceringsstatus ska gälla')
console.log('Publication state checks: OK')
