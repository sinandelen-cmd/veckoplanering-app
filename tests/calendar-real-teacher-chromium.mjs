import assert from 'node:assert/strict'
import {chromium} from 'playwright'
const browser=await chromium.launch({headless:true,args:['--no-sandbox']})
try {
 const page=await browser.newPage()
 await page.route('**/*',route=>['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort('blockedbyclient'))
 await page.goto('http://127.0.0.1:4177/tests/calendar-real-teacher-fixture.html')
 await page.getByRole('heading',{name:'Klasser och schema'}).waitFor()
 const read=async id=>JSON.parse(await page.getByTestId(id).textContent())
 const base=await read('teacher-plan')
 const globalStudent=await read('student-plan')
 assert.deepEqual(globalStudent.schoolClosures[0].classNames,['8B'])
 assert.equal((await read('8A-schedule'))[3].date,'2026-10-22')
 assert.equal((await read('8B-schedule'))[3].date,'2026-10-23')
 console.log('PASS teacher/student: globally scoped school closure affects only 8B')

 // Read-only diagnostics must show saved lesson days and date-specific reasons.
 const diagnostics=page.getByTestId('class-week-diagnostics')
 await diagnostics.locator('summary').click()
 await diagnostics.getByText(/Startdatum:/).waitFor()
 const comparison=diagnostics.getByTestId('class-start-date-comparison')
 await comparison.getByText(/Sparat startdatum:.*2026-10-19/).waitFor()
 await comparison.getByText(/Första lektionen ligger i klassens startvecka/).waitFor()
 await diagnostics.getByText(/Måndag 2026-10-19: 1 planerad/).waitFor()
 await diagnostics.getByText(/Torsdag 2026-10-22: 1 planerad.*schemalagd dag/).waitFor()
 await diagnostics.getByText(/Vecka 44 \(2026-10-26/).waitFor()
 await diagnostics.getByText(/Veckan saknas i Grundplaneringens sparade veckounderlag/).first().waitFor()
 assert.deepEqual(await read('teacher-plan'),base)
 console.log('PASS teacher: read-only weekly diagnostics shows missing calendar weeks and class days without changing plan')
 const add=async(type,start,end=start)=>{
   const toggle=page.getByRole('button',{name:/studiedag \/ halvdag \/ lov/})
   if((await toggle.getAttribute('aria-expanded'))!=='true')await toggle.click()
   await page.getByLabel('Typ').selectOption(type)
   await page.getByLabel('Från datum').fill(start)
   await page.getByLabel('Till datum').fill(end)
   await page.getByRole('button',{name:'+ Lägg till',exact:true}).click()
 }
 await add('Studiedag','2026-10-19')
 assert.equal((await read('8A-schedule'))[0].date,'2026-10-20')
 assert.equal((await read('8B-schedule'))[0].date,'2026-10-19')
 assert.equal((await read('student-plan')).classGroups[0].schoolClosures[0].type,'Studiedag')
 console.log('PASS teacher 8A: study day, student serialization, 8B isolation')
 await page.getByRole('button',{name:'Ta bort Studiedag 2026-10-19'}).click()
 assert.equal((await read('8A-schedule'))[0].date,'2026-10-19')
 console.log('PASS teacher: remove closure restores lesson schedule')
 await add('Lov','2026-10-19','2026-10-23')
 assert.equal((await read('8A-schedule'))[0].date,'2026-10-26')
 assert.equal((await read('8A-schedule')).at(-1).date,'2026-10-29')
 assert.equal((await read('8B-schedule'))[0].date,'2026-10-19')
 console.log('PASS teacher 8A: holiday pushes lessons to new week without affecting 8B')
 await page.getByRole('button',{name:'Ta bort Lov 2026-10-19'}).click()
 await page.getByRole('button',{name:'8B',exact:true}).click()
 await add('Halvdag','2026-10-19')
 assert.equal((await read('8B-schedule'))[0].date,'2026-10-20')
 assert.equal((await read('8A-schedule'))[0].date,'2026-10-19')
 console.log('PASS teacher 8B: half-day closure isolated from 8A')
 const after=await read('teacher-plan')
 assert.deepEqual(after.weeksData,base.weeksData)
 assert.equal(after.classGroups[0].schoolClosures.length,0)
 assert.equal(after.classGroups[1].schoolClosures.length,1)
 console.log('PASS teacher: original lesson content and class data preserved')
 
 // Select 8B from the student-facing picker and verify the schedule editor follows.
 await page.getByRole('button',{name:'Elevvy 8B'}).click()
 assert.equal(await page.getByTestId('active-class').textContent(),'8B')
 assert.equal(await page.getByRole('button',{name:'8B',exact:true}).getAttribute('aria-pressed'),'true')
 await page.getByRole('button',{name:'8A',exact:true}).click()
 assert.equal(await page.getByTestId('active-class').textContent(),'8A')
 console.log('PASS teacher: class selection stays synchronized in both directions')
 // Opening diagnostics for a class with a delayed start must not align dates.
 await page.getByRole('button',{name:'Testa senare startdatum'}).click()
 const beforeDiagnostics=await read('teacher-plan')
 await diagnostics.locator('summary').click()
 await diagnostics.locator('summary').click()
 assert.deepEqual(await read('teacher-plan'),beforeDiagnostics)
 assert.equal((await read('8A-schedule'))[0].date,'2026-11-02')
 await diagnostics.getByTestId('class-start-date-comparison').getByText(/Första lektionen ligger i klassens startvecka/).waitFor()
 console.log('PASS teacher: opening and closing diagnostics never changes delayed start date or lessons')
 // Mobile Safari-like touch viewport: tapping the summary must never activate the adjacent start-date action.
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:3,isMobile:true,hasTouch:true})
 try {
   await mobile.route('**/*',route=>['127.0.0.1','localhost'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort('blockedbyclient'))
   await mobile.goto('http://127.0.0.1:4177/tests/calendar-real-teacher-fixture.html')
   await mobile.getByRole('heading',{name:'Klasser och schema'}).waitFor()
   await mobile.getByRole('button',{name:'Testa senare startdatum'}).click()
   const mobileRead=async id=>JSON.parse(await mobile.getByTestId(id).textContent())
   const mobileBefore=await mobileRead('teacher-plan')
   const mobileDiagnostics=mobile.getByTestId('class-week-diagnostics')
   const mobileSummary=mobileDiagnostics.locator('summary')
   await mobileSummary.tap()
   assert.equal(await mobileDiagnostics.evaluate(element=>element.open),true)
   await mobileSummary.tap()
   assert.equal(await mobileDiagnostics.evaluate(element=>element.open),false)
   assert.deepEqual(await mobileRead('teacher-plan'),mobileBefore)
   assert.equal((await mobileRead('8A-schedule'))[0].date,'2026-11-02')
   console.log('PASS mobile touch: diagnostic summary opens and closes without aligning start date')
 } finally { await mobile.close() }


 await page.getByText(/8A börjar 2026-11-02/).waitFor()
 assert.equal((await read('8A-schedule'))[0].date,'2026-11-02')
 // Merely switching between class tabs must never change either saved start date.
 const beforeSwitch=await read('teacher-plan')
 await page.getByRole('button',{name:'8B',exact:true}).click()
 await page.getByRole('button',{name:'8A',exact:true}).click()
 assert.deepEqual(await read('teacher-plan'),beforeSwitch)
 assert.equal((await read('8A-schedule'))[0].date,'2026-11-02')
 console.log('PASS teacher: switching 8A/8B preserves all saved class start dates')
 // The alignment action must require explicit consent; cancel must preserve data.
 const alignButton=page.getByRole('button',{name:/Använd grundplaneringens startdatum för 8A/})
 page.once('dialog',async dialog=>{
   assert.match(dialog.message(),/8A.*2026-11-02.*2026-10-19/)
   await dialog.dismiss()
 })
 await alignButton.click()
 assert.deepEqual(await read('teacher-plan'),beforeSwitch)
 assert.equal((await read('8A-schedule'))[0].date,'2026-11-02')
 console.log('PASS teacher: cancelled start-date confirmation never modifies plan')
 page.once('dialog',dialog=>dialog.accept())
 await alignButton.click()
 assert.equal((await read('8A-schedule'))[0].date,'2026-10-19')
 console.log('PASS teacher: delayed class start explained and manually aligned without changing source')
}finally{await browser.close()}
